fn table(lang: &str) -> Option<&'static [(&'static str, &'static str)]> {
    match lang {
        "en" => Some(EN),
        "pt_BR" => Some(PT_BR),
        "es" => Some(ES),
        "de" => Some(DE),
        "fr" => Some(FR),
        "ja" => Some(JA),
        _ => None,
    }
}

fn find(t: &[(&str, &'static str)], key: &str) -> Option<&'static str> {
    t.iter().find(|(k, _)| *k == key).map(|(_, v)| *v)
}

/// Translate `key`, falling back to English and then to the key itself.
pub fn translate(key: &str, lang: &str) -> String {
    table(lang)
        .and_then(|t| find(t, key))
        .or_else(|| table("en").and_then(|t| find(t, key)))
        .unwrap_or(key)
        .to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn falls_back_to_english_then_key() {
        assert_eq!(translate("nav_overview", "en"), "Overview");
        assert_eq!(translate("nav_overview", "xx"), "Overview");
        assert_eq!(translate("no_such_key", "en"), "no_such_key");
    }

    #[test]
    fn every_language_has_the_english_keys() {
        for (code, _) in LANGUAGES.iter().skip(1) {
            assert!(table(code).is_some(), "{code} missing");
        }
    }
}
